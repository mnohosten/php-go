<?php
// Example: Variable Assignment and Types
// This demonstrates basic variable operations in PHP

// Integer assignment
$number = 42;
echo "Integer: ";
echo $number;
echo "\n";

// String assignment
$message = "Hello, PHP-Go!";
echo "String: ";
echo $message;
echo "\n";

// Float assignment
$pi = 3.14159;
echo "Float: ";
echo $pi;
echo "\n";

// Boolean
$isTrue = true;
$isFalse = false;
echo "Boolean true: ";
echo $isTrue;  // Outputs: 1
echo "\n";
echo "Boolean false: ";
echo $isFalse; // Outputs: (empty)
echo "\n";

// Variable reassignment
$x = 5;
echo "Initial value: ";
echo $x;
echo "\n";
$x = 10;
echo "After reassignment: ";
echo $x;
echo "\n";

// Multiple variables
$a = 1;
$b = 2;
$c = 3;
echo "Multiple variables: ";
echo $a;
echo ", ";
echo $b;
echo ", ";
echo $c;
echo "\n";
